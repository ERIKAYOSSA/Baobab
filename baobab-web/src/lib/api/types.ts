export type FamilyTreeEdge = {
  type: string;
  fromPersonId: string;
  toPersonId: string;
  autoGenerated?: boolean;
  line?: string;
  sharedLine?: string;
  uiLabel?: string;
  official?: boolean;
};

export type FamilyTreeNode = ApiPerson & {
  generation: number;
  roles: string[];
  ui: {
    label: string;
    group: "self" | "ancestor" | "descendant" | "spouse" | "collateral";
  };
};

export type FamilyTreeResult = {
  root: FamilyTreeNode;
  nodes: FamilyTreeNode[];
  edges: FamilyTreeEdge[];
  meta: {
    depth: number;
    generations: number[];
    counts: {
      ancestors: number;
      descendants: number;
      spouses: number;
      collateral: number;
    };
  };
};


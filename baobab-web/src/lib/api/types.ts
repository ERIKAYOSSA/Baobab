export type NotificationsPayload = {
  pendingApprovals: Array<{
    type: "approval_required";
    requestId: string;
    requestType: string;
    /** Qui a fait la demande. */
    requester: NotificationPerson | null;
    /** Le lien demandé : « from » est <type> de « to ». */
    from: NotificationPerson | null;
    to: NotificationPerson | null;
    createdAt: string | null;
  }>;
  myRequests: Array<{
    type: "my_request";
    requestId: string;
    status: string;
    relationshipType: string;
    fromPersonId: string;
    toPersonId: string;
    from: NotificationPerson | null;
    to: NotificationPerson | null;
    pendingVotes: number;
    approvedVotes: number;
    totalVotes: number;
    /** Réponses des membres à qui la demande a été soumise. */
    votes: Array<{
      id: string;
      firstName: string;
      lastName: string;
      status: "pending" | "approved" | "rejected" | string;
      decidedAt: string | null;
    }>;
    decidedAt: string | null;
    createdAt: string | null;
  }>;
  summary: {
    pendingApprovalsCount: number;
    myPendingRequestsCount: number;
  };
};


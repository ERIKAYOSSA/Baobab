export type MaritalStatus = "single" | "married" | "widowed" | "divorced" | "unknown";
export type SocialTitle = "chief" | "elder" | "notable";

export type ApiPerson = {
  id: string;
  /** Vrai si la personne a un compte avec téléphone vérifié (le numéro lui-même n'est jamais affiché aux autres). */
  hasPhone?: boolean;
  /** Qui a ajouté ce profil (proches sans compte) et état du compte. */
  createdBy?: string | null;
  accountStatus?: string | null;
  firstName: string;
  lastName: string;
  gender?: "male" | "female" | "other" | null;
  birthDate?: string | null;
  deathDate?: string | null;
  village?: string | null;
  phone?: string | null;
  createdAt?: string;
  updatedAt?: string;
  /** True when a PIN is configured (never expose the hash). */
  hasPin?: boolean;
  /** Profile photo set from "Moi" — shown in Mon Arbre. */
  photoUrl?: string | null;
  nickname?: string | null;
  honorifics?: string[] | null;
  socialTitle?: SocialTitle | null;
  headOfFamily?: boolean | null;
  maritalStatus?: MaritalStatus | null;
  residence?: string | null;
  burialPlace?: string | null;
  ethnicity?: string | null;
  clan?: string | null;
  totem?: string | null;
  languages?: string[] | null;
  nationalities?: string[] | null;
  religion?: string | null;
  initiations?: string | null;
  oralHistory?: string | null;
  birthCountry?: string | null;
  birthCity?: string | null;
  birthQuarter?: string | null;
  /** Préférences de découverte (absent = activé, sauf receiveInvites). */
  appearInSuggestions?: boolean | null;
  detectLinks?: boolean | null;
  receiveInvites?: boolean | null;
};


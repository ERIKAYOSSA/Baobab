/**
 * Seed script for Baobab family dataset (Diallo).
 * Usage: npm run seed
 * Requires Neo4j running and .env configured.
 */
import "dotenv/config";
import neo4j from "neo4j-driver";

const uri = process.env.NEO4J_URI ?? "bolt://localhost:7687";
const user = process.env.NEO4J_USER ?? "neo4j";
const password = process.env.NEO4J_PASSWORD;

if (!password) {
  console.error("Missing NEO4J_PASSWORD in .env");
  process.exit(1);
}

const driver = neo4j.driver(uri, neo4j.auth.basic(user, password));

async function seed() {
  const session = driver.session();
  try {
    await session.run(`MATCH (n) DETACH DELETE n`);

    await session.run(`
      CREATE (moussa:Person {id: randomUUID(), firstName:'Moussa', lastName:'Diallo', gender:'male', birthDate:'1940-09-20', deathDate:'2010-03-15', village:'Bobo-Dioulasso', phone:'+22670123401', createdAt: datetime()})
      CREATE (fatoumata:Person {id: randomUUID(), firstName:'Fatoumata', lastName:'Diallo', gender:'female', birthDate:'1945-03-12', deathDate:'2018-11-02', village:'Bobo-Dioulasso', createdAt: datetime()})
      CREATE (ibrahim:Person {id: randomUUID(), firstName:'Ibrahim', lastName:'Diallo', gender:'male', birthDate:'1965-11-08', village:'Bobo-Dioulasso', phone:'+22670123402', createdAt: datetime()})
      CREATE (amina:Person {id: randomUUID(), firstName:'Amina', lastName:'Diallo', gender:'female', birthDate:'1995-06-01', village:'Bobo-Dioulasso', phone:'+22670123403', createdAt: datetime()})
      CREATE (kadidia:Person {id: randomUUID(), firstName:'Kadidia', lastName:'Diallo', gender:'female', birthDate:'1998-04-15', village:'Bobo-Dioulasso', createdAt: datetime()})
      CREATE (moussa)-[:FATHER_OF {createdAt: datetime()}]->(ibrahim)
      CREATE (moussa)-[:FATHER_OF {createdAt: datetime()}]->(amina)
      CREATE (moussa)-[:FATHER_OF {createdAt: datetime()}]->(kadidia)
      CREATE (fatoumata)-[:MOTHER_OF {createdAt: datetime()}]->(ibrahim)
      CREATE (fatoumata)-[:MOTHER_OF {createdAt: datetime()}]->(amina)
      CREATE (fatoumata)-[:MOTHER_OF {createdAt: datetime()}]->(kadidia)
      CREATE (fatoumata)-[:WIFE_OF {createdAt: datetime()}]->(moussa)
      CREATE (ibrahim)-[:FULL_SIBLING_OF {autoGenerated:true, consanguinity:'full', createdAt: datetime()}]->(amina)
      CREATE (ibrahim)-[:FULL_SIBLING_OF {autoGenerated:true, consanguinity:'full', createdAt: datetime()}]->(kadidia)
      CREATE (amina)-[:FULL_SIBLING_OF {autoGenerated:true, consanguinity:'full', createdAt: datetime()}]->(kadidia)
      RETURN moussa.id AS moussaId, amina.id AS aminaId
    `);

    const count = await session.run(`MATCH (p:Person) RETURN count(p) AS c`);
    const persons = count.records[0].get("c");
    const total = typeof persons === "object" && persons !== null && "low" in persons ? persons.low : persons;

    console.log(`Seed complete: ${total} persons created (famille Diallo).`);
  } finally {
    await session.close();
    await driver.close();
  }
}

seed().catch((err) => {
  console.error("Seed failed:", err);
  process.exit(1);
});

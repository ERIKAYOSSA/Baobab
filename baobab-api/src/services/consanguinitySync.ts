import { Session } from "neo4j-driver";

/**
 * Converts legacy PARENT_OF links into explicit FATHER_OF / MOTHER_OF when gender is known.
 */
export async function migrateLegacyParentLinks(session: Session): Promise<void> {
  await session.run(
    `
    MATCH (p:Person)-[r:PARENT_OF]->(c:Person)
    WHERE p.gender = 'male'
      AND NOT (p)-[:FATHER_OF]->(c)
    CREATE (p)-[:FATHER_OF {migratedFrom: 'PARENT_OF', createdAt: coalesce(r.createdAt, datetime())}]->(c)
    `
  );
  await session.run(
    `
    MATCH (p:Person)-[r:PARENT_OF]->(c:Person)
    WHERE p.gender = 'female'
      AND NOT (p)-[:MOTHER_OF]->(c)
    CREATE (p)-[:MOTHER_OF {migratedFrom: 'PARENT_OF', createdAt: coalesce(r.createdAt, datetime())}]->(c)
    `
  );
}

async function countCreated(session: Session, result: { records: { get: (k: string) => unknown }[] }) {
  const createdCount = result.records[0]?.get("createdCount");
  if (typeof createdCount === "object" && createdCount !== null && "low" in createdCount) {
    return (createdCount as { low: number }).low;
  }
  return Number(createdCount ?? 0);
}

export async function syncConsanguinityRelationships(session: Session): Promise<{
  fullSiblings: number;
  halfSiblings: number;
  cousins: number;
}> {
  await migrateLegacyParentLinks(session);

  await session.run(
    `
    MATCH ()-[r:FULL_SIBLING_OF|HALF_SIBLING_OF|COUSIN_OF {autoGenerated: true}]->()
    DELETE r
    `
  );

  const fullSiblings = await countCreated(
    session,
    await session.run(
      `
      MATCH (a:Person), (b:Person)
      WHERE a.id < b.id
      MATCH (f:Person)-[:FATHER_OF]->(a)
      MATCH (f)-[:FATHER_OF]->(b)
      MATCH (m:Person)-[:MOTHER_OF]->(a)
      MATCH (m)-[:MOTHER_OF]->(b)
      CREATE (a)-[r:FULL_SIBLING_OF {
        autoGenerated: true,
        consanguinity: 'full',
        createdAt: datetime()
      }]->(b)
      RETURN count(r) AS createdCount
      `
    )
  );

  const halfPaternal = await countCreated(
    session,
    await session.run(
      `
      MATCH (a:Person), (b:Person)
      WHERE a.id < b.id
      MATCH (f:Person)-[:FATHER_OF]->(a)
      MATCH (f)-[:FATHER_OF]->(b)
      WHERE NOT EXISTS {
        MATCH (m:Person)-[:MOTHER_OF]->(a)
        MATCH (m)-[:MOTHER_OF]->(b)
      }
      AND NOT (a)-[:FULL_SIBLING_OF|SIBLING_OF]-(b)
      AND NOT (b)-[:FULL_SIBLING_OF|SIBLING_OF]->(a)
      CREATE (a)-[r:HALF_SIBLING_OF {
        autoGenerated: true,
        consanguinity: 'half',
        sharedLine: 'paternal',
        createdAt: datetime()
      }]->(b)
      RETURN count(r) AS createdCount
      `
    )
  );

  const halfMaternal = await countCreated(
    session,
    await session.run(
      `
      MATCH (a:Person), (b:Person)
      WHERE a.id < b.id
      MATCH (m:Person)-[:MOTHER_OF]->(a)
      MATCH (m)-[:MOTHER_OF]->(b)
      WHERE NOT EXISTS {
        MATCH (f:Person)-[:FATHER_OF]->(a)
        MATCH (f)-[:FATHER_OF]->(b)
      }
      AND NOT (a)-[:FULL_SIBLING_OF|HALF_SIBLING_OF|SIBLING_OF]-(b)
      AND NOT (b)-[:FULL_SIBLING_OF|HALF_SIBLING_OF|SIBLING_OF]->(a)
      CREATE (a)-[r:HALF_SIBLING_OF {
        autoGenerated: true,
        consanguinity: 'half',
        sharedLine: 'maternal',
        createdAt: datetime()
      }]->(b)
      RETURN count(r) AS createdCount
      `
    )
  );

  const cousinsPaternal = await countCreated(
    session,
    await session.run(
      `
      MATCH (a:Person), (b:Person)
      WHERE a.id < b.id
      MATCH (a)<-[:FATHER_OF]-(dad:Person)
      MATCH (dad)-[:SIBLING_OF]-(uncle:Person)
      MATCH (uncle)-[:FATHER_OF]->(b)
      WHERE NOT (a)-[:FULL_SIBLING_OF|HALF_SIBLING_OF|SIBLING_OF]-(b)
        AND NOT (a)<-[:FATHER_OF|MOTHER_OF|PARENT_OF]-(b)
        AND NOT (a)-[:FATHER_OF|MOTHER_OF|PARENT_OF]->(b)
      CREATE (a)-[r:COUSIN_OF {
        autoGenerated: true,
        degree: 1,
        line: 'paternal',
        createdAt: datetime()
      }]->(b)
      RETURN count(r) AS createdCount
      `
    )
  );

  const cousinsMaternal = await countCreated(
    session,
    await session.run(
      `
      MATCH (a:Person), (b:Person)
      WHERE a.id < b.id
      MATCH (a)<-[:MOTHER_OF]-(mom:Person)
      MATCH (mom)-[:SIBLING_OF]-(aunt:Person)
      MATCH (aunt)-[:MOTHER_OF]->(b)
      WHERE NOT (a)-[:FULL_SIBLING_OF|HALF_SIBLING_OF|SIBLING_OF]-(b)
        AND NOT (a)<-[:FATHER_OF|MOTHER_OF|PARENT_OF]-(b)
        AND NOT (a)-[:FATHER_OF|MOTHER_OF|PARENT_OF]->(b)
        AND NOT (a)-[:COUSIN_OF {line: 'paternal'}]->(b)
      CREATE (a)-[r:COUSIN_OF {
        autoGenerated: true,
        degree: 1,
        line: 'maternal',
        createdAt: datetime()
      }]->(b)
      RETURN count(r) AS createdCount
      `
    )
  );

  const cousinsBoth = await countCreated(
    session,
    await session.run(
      `
      MATCH (a:Person), (b:Person)
      WHERE a.id < b.id
      MATCH (a)<-[:FATHER_OF]-(dad:Person)-[:SIBLING_OF]-(uncle:Person)-[:FATHER_OF]->(b)
      MATCH (a)<-[:MOTHER_OF]-(mom:Person)-[:SIBLING_OF]-(aunt:Person)-[:MOTHER_OF]->(b)
      MERGE (a)-[r:COUSIN_OF]->(b)
      SET r.autoGenerated = true,
          r.degree = 1,
          r.line = 'both',
          r.createdAt = coalesce(r.createdAt, datetime())
      RETURN count(r) AS createdCount
      `
    )
  );

  return {
    fullSiblings,
    halfSiblings: halfPaternal + halfMaternal,
    cousins: cousinsPaternal + cousinsMaternal + cousinsBoth
  };
}

import { Session } from "neo4j-driver";

type PersonNode = Record<string, unknown>;

export type FamilyTreeEdge = {
  type: string;
  fromPersonId: string;
  toPersonId: string;
  autoGenerated?: boolean;
  line?: string;
  sharedLine?: string;
  uiLabel?: string;
  official?: boolean;
};

export type FamilyTreeNode = PersonNode & {
  generation: number;
  roles: string[];
  ui: {
    label: string;
    group: "self" | "ancestor" | "descendant" | "spouse" | "collateral";
  };
};

export type FamilyTreeResult = {
  root: FamilyTreeNode;
  nodes: FamilyTreeNode[];
  edges: FamilyTreeEdge[];
  meta: {
    depth: number;
    generations: number[];
    counts: {
      ancestors: number;
      descendants: number;
      spouses: number;
      collateral: number;
    };
  };
};

const TREE_REL_TYPES = [
  "PARENT_OF",
  "FATHER_OF",
  "MOTHER_OF",
  "HUSBAND_OF",
  "WIFE_OF",
  "MARRIED_TO",
  "CO_WIFE_OF",
  "SIBLING_OF",
  "FULL_SIBLING_OF",
  "HALF_SIBLING_OF",
  "COUSIN_OF"
];

const PARENT_TYPES = new Set(["PARENT_OF", "FATHER_OF", "MOTHER_OF"]);
const SPOUSE_TYPES = new Set(["HUSBAND_OF", "WIFE_OF", "MARRIED_TO", "CO_WIFE_OF"]);
const COLLATERAL_TYPES = new Set(["SIBLING_OF", "FULL_SIBLING_OF", "HALF_SIBLING_OF", "COUSIN_OF", "CO_WIFE_OF"]);

function mapPerson(node: { properties: Record<string, unknown> } | null): PersonNode | null {
  return node ? node.properties : null;
}

function edgeLabel(type: string): string {
  const labels: Record<string, string> = {
    FATHER_OF: "Père de",
    MOTHER_OF: "Mère de",
    PARENT_OF: "Parent de",
    HUSBAND_OF: "Époux de",
    WIFE_OF: "Épouse de",
    MARRIED_TO: "Marié(e) à",
    CO_WIFE_OF: "Co-épouse de",
    SIBLING_OF: "Frère/Sœur de",
    FULL_SIBLING_OF: "Germain(e) de",
    HALF_SIBLING_OF: "Demi-frère/sœur de",
    COUSIN_OF: "Cousin(e) de"
  };
  return labels[type] ?? type;
}

function computeRoles(rootId: string, nodeId: string, edges: FamilyTreeEdge[]): string[] {
  if (rootId === nodeId) return ["self"];

  const roles = new Set<string>();
  for (const edge of edges) {
    if (edge.fromPersonId === rootId && edge.toPersonId === nodeId) {
      if (PARENT_TYPES.has(edge.type)) roles.add("child");
      if (SPOUSE_TYPES.has(edge.type)) roles.add("spouse");
      if (COLLATERAL_TYPES.has(edge.type)) roles.add(edge.type === "COUSIN_OF" ? "cousin" : "sibling");
    }
    if (edge.toPersonId === rootId && edge.fromPersonId === nodeId) {
      if (PARENT_TYPES.has(edge.type)) roles.add(edge.type === "FATHER_OF" ? "father" : edge.type === "MOTHER_OF" ? "mother" : "parent");
      if (SPOUSE_TYPES.has(edge.type)) roles.add("spouse");
      if (COLLATERAL_TYPES.has(edge.type)) roles.add(edge.type === "COUSIN_OF" ? "cousin" : "sibling");
    }
  }

  return roles.size > 0 ? [...roles] : ["relative"];
}

function computeGenerations(rootId: string, edges: FamilyTreeEdge[]): Map<string, number> {
  const generations = new Map<string, number>([[rootId, 0]]);
  let changed = true;

  while (changed) {
    changed = false;
    for (const edge of edges) {
      if (PARENT_TYPES.has(edge.type)) {
        const parentId = edge.fromPersonId;
        const childId = edge.toPersonId;
        if (generations.has(parentId) && !generations.has(childId)) {
          generations.set(childId, generations.get(parentId)! + 1);
          changed = true;
        }
        if (generations.has(childId) && !generations.has(parentId)) {
          generations.set(parentId, generations.get(childId)! - 1);
          changed = true;
        }
      } else if (SPOUSE_TYPES.has(edge.type) || COLLATERAL_TYPES.has(edge.type)) {
        const a = edge.fromPersonId;
        const b = edge.toPersonId;
        if (generations.has(a) && !generations.has(b)) {
          generations.set(b, generations.get(a)!);
          changed = true;
        }
        if (generations.has(b) && !generations.has(a)) {
          generations.set(a, generations.get(b)!);
          changed = true;
        }
      }
    }
  }

  return generations;
}

function uiGroup(roles: string[], generation: number): FamilyTreeNode["ui"]["group"] {
  if (roles.includes("self")) return "self";
  if (roles.includes("father") || roles.includes("mother") || roles.includes("parent") || generation < 0) {
    return "ancestor";
  }
  if (roles.includes("child") || generation > 0) return "descendant";
  if (roles.includes("spouse")) return "spouse";
  return "collateral";
}

export async function buildFamilyTree(
  session: Session,
  personId: string,
  depth = 2
): Promise<FamilyTreeResult | null> {
  const boundedDepth = Math.min(Math.max(depth, 1), 4);

  const rootResult = await session.run(`MATCH (p:Person {id: $personId}) RETURN p`, { personId });
  if (rootResult.records.length === 0) return null;

  const rootProps = mapPerson(rootResult.records[0].get("p"))!;

  const graphResult = await session.run(
    `
    MATCH (seed:Person {id: $personId})
    MATCH path = (seed)-[r*1..${boundedDepth}]-(related:Person)
    WHERE ALL(rel IN relationships(path) WHERE type(rel) IN $relTypes)
    UNWIND relationships(path) AS rel
    WITH startNode(rel) AS a, endNode(rel) AS b, rel
    RETURN DISTINCT a, b, type(rel) AS relType, rel AS relationship
    `,
    { personId, relTypes: TREE_REL_TYPES }
  );

  const nodeMap = new Map<string, PersonNode>();
  nodeMap.set(rootProps.id as string, rootProps);

  const edgeKey = new Set<string>();
  const edges: FamilyTreeEdge[] = [];

  for (const record of graphResult.records) {
    const a = mapPerson(record.get("a"));
    const b = mapPerson(record.get("b"));
    if (!a || !b) continue;

    nodeMap.set(a.id as string, a);
    nodeMap.set(b.id as string, b);

    const rel = record.get("relationship") as { properties?: Record<string, unknown> };
    const relType = record.get("relType") as string;
    const fromPersonId = a.id as string;
    const toPersonId = b.id as string;
    const key = `${relType}:${fromPersonId}:${toPersonId}`;

    if (edgeKey.has(key)) continue;
    edgeKey.add(key);

    edges.push({
      type: relType,
      fromPersonId,
      toPersonId,
      autoGenerated: rel.properties?.autoGenerated as boolean | undefined,
      line: rel.properties?.line as string | undefined,
      sharedLine: rel.properties?.sharedLine as string | undefined,
      uiLabel: (rel.properties?.partyAppellation as string | undefined) || edgeLabel(relType),
      official: rel.properties?.official === false ? false : undefined
    });
  }

  const rootId = rootProps.id as string;
  const generationMap = computeGenerations(rootId, edges);

  const nodes: FamilyTreeNode[] = [...nodeMap.values()].map((person) => {
    const id = person.id as string;
    const generation = generationMap.get(id) ?? 0;
    const roles = computeRoles(rootId, id, edges);
    const firstName = String(person.firstName ?? "");
    const lastName = String(person.lastName ?? "");
    const group = uiGroup(roles, generation);

    return {
      ...person,
      generation,
      roles,
      ui: {
        label: `${firstName} ${lastName}`.trim(),
        group
      }
    };
  });

  const root = nodes.find((n) => n.id === rootId)!;
  const generations = [...new Set(nodes.map((n) => n.generation))].sort((a, b) => a - b);

  return {
    root,
    nodes,
    edges,
    meta: {
      depth: boundedDepth,
      generations,
      counts: {
        ancestors: nodes.filter((n) => n.ui.group === "ancestor").length,
        descendants: nodes.filter((n) => n.ui.group === "descendant").length,
        spouses: nodes.filter((n) => n.ui.group === "spouse").length,
        collateral: nodes.filter((n) => n.ui.group === "collateral").length
      }
    }
  };
}
